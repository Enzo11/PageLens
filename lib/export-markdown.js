/* PageLens — lib/export-markdown.js
 * Renders a report model (lib/report-model.js) as GitHub-flavoured Markdown.
 * Pure.
 */
(function (root) {
  'use strict';

  const SEV = { critical: 'Critical', high: 'High', medium: 'Medium', low: 'Low' };
  const EFFORT = { quick: 'quick fix', moderate: 'some work', involved: 'bigger job' };
  const cell = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
  const esc = (s) => String(s == null ? '' : s).replace(/([\\`*_[\]<>])/g, '\\$1');

  function block(b, L) {
    if (b.title) L.push(`**${esc(b.title)}**`, '');
    switch (b.type) {
      case 'p': L.push(esc(b.text), ''); break;
      case 'note': L.push(`> ${esc(b.text)}`, ''); break;
      case 'score': L.push(`**${b.value}/${b.max}** · ${esc(b.label)}${b.note ? ` — ${esc(b.note)}` : ''}`, ''); break;
      case 'kv':
        L.push('| | |', '|---|---|');
        for (const [k, v] of b.rows) L.push(`| ${cell(k)} | ${cell(v)} |`);
        L.push('');
        break;
      case 'table':
        L.push(`| ${b.head.map(cell).join(' | ')} |`, `|${b.head.map((_, i) => ((b.num || []).includes(i) ? '---:' : '---')).join('|')}|`);
        for (const r of b.rows) L.push(`| ${r.map(cell).join(' | ')} |`);
        L.push('');
        break;
      case 'bars':
        for (const x of b.items) L.push(`- ${esc(x.label)}: **${x.value}/${x.max}**`);
        L.push('');
        break;
      case 'list':
        for (const x of b.items) {
          const it = typeof x === 'string' ? { text: x } : x;
          const mark = it.tone === 'good' ? '✅ ' : it.tone === 'bad' ? '⚠️ ' : '';
          L.push(`${'  '.repeat(it.level || 0)}- ${mark}${esc(it.text)}${it.sub ? ` — ${esc(it.sub)}` : ''}`);
        }
        L.push('');
        break;
      case 'chips': L.push(b.items.map((x) => `\`${String(x).replace(/`/g, "'")}\``).join(' · '), ''); break;
      case 'palette':
        L.push('| Color | Share | Role |', '|---|---:|---|');
        for (const p of b.items) L.push(`| \`${p.hex}\` | ${(p.share * 100).toFixed(1)}% | ${p.role} |`);
        L.push('');
        break;
      case 'outline':
        for (const x of b.items) L.push(`${'  '.repeat(x.level - 1)}- H${x.level} ${esc(x.text)}`);
        L.push('');
        break;
      case 'code':
        if (b.caption) L.push(esc(b.caption), '');
        L.push('```' + (b.lang || ''), b.text, '```', '');
        break;
      case 'issues':
        for (const i of b.items) {
          L.push(`- **${esc(i.title)}** _(${SEV[i.severity]}, ${EFFORT[i.effort]})_`);
          if (b.detail) {
            L.push(`  - Why: ${esc(i.why)}`);
            L.push(`  - Fix: ${esc(i.fix)}`);
            if (i.whereText) L.push(`  - Where: ${esc(i.whereText)}`);
            if (i.ref) L.push(`  - Reference: ${esc(i.ref)}`);
          }
        }
        L.push('');
        break;
      default:
        break;
    }
  }

  function render(model) {
    const L = [`# ${esc(model.title)}`, ''];
    if (model.subtitle) L.push(`_${esc(model.subtitle)}_`, '');
    L.push(model.meta.map(esc).join('  \n'), '');
    L.push('## Contents', '');
    model.sections.forEach((s, i) => L.push(`${i + 1}. [${esc(s.title)}](#${s.id})`));
    L.push('');
    for (const s of model.sections) {
      L.push(`<a id="${s.id}"></a>`, '', `## ${esc(s.title)}`, '');
      for (const b of s.blocks) block(b, L);
    }
    L.push('---', '', 'Generated by PageLens — free, open-source, rule-based. Same input, same result.', '');
    return L.join('\n');
  }

  root.PageLensMarkdown = Object.freeze({ render });
})(globalThis);
